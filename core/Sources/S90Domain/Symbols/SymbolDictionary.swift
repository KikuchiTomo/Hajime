/// 続けて打った記号を 1 つの記号にまとめる規則．「->」(ー＞)を「→」に，「<-」(＜ー)を「←」にする
public enum SymbolSequence {
    /// 並びと，まとめた記号．長い並びを先に調べる
    private static let rules: [(sequence: String, symbol: String)] = [
        ("←＞", "↔"), ("⇐＞", "⇔"),
        ("ー＞", "→"), ("＜ー", "←"), ("＝＞", "⇒"), ("＜＝", "⇐"),
    ]

    /// 末尾の並びがまとめられるなら，まとめる並びの長さと記号を返す
    public static func match(suffixOf text: String) -> (length: Int, symbol: String)? {
        rules.first { text.hasSuffix($0.sequence) }.map { ($0.sequence.count, $0.symbol) }
    }
}
